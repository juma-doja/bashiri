def generate_saved_markets_pdf(saved_markets, tab_name="All Markets"):
    """
    Generate a PDF document with saved markets data.
    
    Args:
        saved_markets: List of saved market dictionaries with match and AI data
        tab_name: Name of the tab/category being generated
    
    Returns:
        BytesIO: PDF file content
    """
    buffer = BytesIO()
    
    # Generate unique document ID
    document_id = str(uuid.uuid4())[:8].upper()
    
    # Custom page function to add watermark and page numbers
    def add_page_footer(canvas, doc):
        # Add page number
        page_num = canvas.getPageNumber()
        canvas.setFont('Helvetica', 9)
        canvas.setFillColor(colors.HexColor('#999999'))
        page_text = f"Page {page_num}"
        text_width = canvas.stringWidth(page_text, 'Helvetica', 9)
        
        # Draw centered at bottom
        canvas.drawString(
            (A4[0] - text_width) / 2,
            0.75 * cm,
            page_text
        )
        
        # Add premium watermark logo with better visibility
        try:
            # Try to find the Bashiri logo in the frontend public directory
            logo_path = os.path.join(os.path.dirname(__file__), '..', '..', 'frontend', 'public', 'bashiri-mark-gold.svg')
            if not os.path.exists(logo_path):
                # Fallback to app icon
                logo_path = os.path.join(os.path.dirname(__file__), '..', '..', 'frontend', 'public', 'bashiri-app-icon-192.png')
            
            if os.path.exists(logo_path):
                canvas.saveState()
                # Set better transparency for visible but subtle watermark
                canvas.setFillAlpha(0.15)  # 15% opacity - more visible
                # Center the logo on the page
                page_width, page_height = A4
                logo = Image(logo_path, width=8*cm, height=8*cm)  # Smaller but cleaner
                logo.drawOn(canvas, (page_width - 8*cm) / 2, (page_height - 8*cm) / 2)
                canvas.restoreState()
        except Exception:
            # If logo not found, skip watermark
            pass
    
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=2*cm,
        leftMargin=2*cm,
        topMargin=2*cm,
        bottomMargin=1.5*cm,  # Reduced for page numbers
        onFirstPage=add_page_footer,
        onLaterPages=add_page_footer
    )
    
    # Custom styles - PREMIUM TYPOGRAPHY
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'CustomTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',  # Using available bold font
        fontSize=28,  # Increased from 24 for more impact
        textColor=colors.HexColor('#D4AF37'),
        spaceAfter=36,  # Increased spacing
        alignment=TA_CENTER,
        leading=40  # Better line height (1.4x)
    )
    
    subtitle_style = ParagraphStyle(
        'CustomSubtitle',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=18,  # Increased from 16
        textColor=colors.HexColor('#CFAF7B'),
        spaceAfter=24,  # Increased spacing
        alignment=TA_CENTER,
        leading=26  # Better line height (1.4x)
    )
    
    normal_style = ParagraphStyle(
        'CustomNormal',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=12,
        textColor=colors.HexColor('#333333'),
        spaceAfter=14,  # Increased spacing
        leading=18  # 1.5 line spacing
    )
    
    header_style = ParagraphStyle(
        'CustomHeader',
        parent=styles['Heading3'],
        fontName='Helvetica-Bold',
        fontSize=16,  # Increased from 14
        textColor=colors.HexColor('#D4AF37'),
        spaceAfter=12,  # Increased spacing
        spaceBefore=24,  # Increased spacing before
        leading=22  # Better line height (1.4x)
    )
    
    market_style = ParagraphStyle(
        'CustomMarket',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=12,
        textColor=colors.HexColor('#666666'),
        spaceAfter=10,  # Increased spacing
        leading=18  # 1.5 line spacing
    )
    
    ai_style = ParagraphStyle(
        'CustomAI',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',  # Bold for AI predictions
        fontSize=12,
        textColor=colors.HexColor('#00FF87'),
        spaceAfter=10,  # Increased spacing
        leading=18  # 1.5 line spacing
    )
    
    # Premium footer style
    footer_style = ParagraphStyle(
        'Footer',
        fontName='Helvetica',
        fontSize=9,  # Increased from 8 for better readability
        textColor=colors.HexColor('#999999'),
        alignment=TA_CENTER,
        leading=12  # Better line height
    )
    
    # Build content
    content = []
    
    # Professional header with gold background
    header_data = [[Paragraph("Bashiri - AI Football Predictions", title_style)]]
    header_table = Table(header_data, colWidths=[17*cm])
    header_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#D4AF37')),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 25),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 25),
    ]))
    content.append(header_table)
    content.append(Spacer(1, 0.4*cm))
    
    # Subtitle with document metadata
    metadata_text = f"""
    <b>Saved Markets - {tab_name}</b><br/>
    Generated: {datetime.now().strftime('%B %d, %Y at %I:%M %p')}<br/>
    Document ID: {document_id}
    """
    content.append(Paragraph(metadata_text, subtitle_style))
    content.append(Spacer(1, 0.6*cm))
    
    # Group by match
    from collections import defaultdict
    grouped = defaultdict(list)
    for market in saved_markets:
        match_id = market['match']['id']
        grouped[match_id].append(market)
    
    # Generate content for each match
    match_count = len(grouped)
    for idx, (match_id, markets) in enumerate(grouped.items()):
        match = markets[0]['match']
        
        # Add section divider for subsequent matches
        if idx > 0:
            content.extend(create_section_divider())
        
        # Match header
        content.append(Paragraph(
            f"{match['home_team']['name']} vs {match['away_team']['name']}",
            header_style
        ))
        content.append(Paragraph(
            f"{match['league']['name']} • {datetime.fromisoformat(match['kickoff_at']).strftime('%B %d, %Y %I:%M %p')}",
            normal_style
        ))
        
        # Markets table
        market_data = [['Market Type', 'AI Prediction', 'Confidence']]
        for market in markets:
            market_key = market['market_key']
            ai_pick = market.get('ai_pick', 'N/A')
            confidence = market.get('ai_confidence')
            conf_str = f"{confidence}%" if confidence else 'N/A'
            
            # Convert market key to readable label (matching production JSON)
            market_labels = {
                # Full Match
                "1X2": "Matokeo ya Mechi",
                "DOUBLE_CHANCE": "Double Chance",
                "DRAW_NO_BET": "Draw No Bet",
                "BTTS": "Timu Zote Kufunga (BTTS)",
                "OVER_UNDER_1_5": "Over/Under 1.5",
                "OVER_UNDER_2_5": "Over/Under 2.5",
                # Home Team Goals
                "HOME_GOALS_OVER_0_5": "Home Over/Under 0.5",
                "HOME_GOALS_OVER_1_5": "Home Over/Under 1.5",
                "HOME_GOALS_OVER_2_5": "Home Over/Under 2.5",
                # Away Team Goals
                "AWAY_GOALS_OVER_0_5": "Away Over/Under 0.5",
                "AWAY_GOALS_OVER_1_5": "Away Over/Under 1.5",
                "AWAY_GOALS_OVER_2_5": "Away Over/Under 2.5",
                # Correct Score
                "CORRECT_SCORE": "Correct Score",
            }
            market_label = market_labels.get(market_key, market_key)
            
            market_data.append([market_label, ai_pick, conf_str])
        
        # Create table with premium styling
        table = Table(market_data, colWidths=[5.5*cm, 4*cm, 2.5*cm])  # Better column distribution
        table.setStyle(create_premium_table_style())
        
        content.append(table)
        content.append(Spacer(1, 0.8*cm))  # Increased spacing between tables
    
    # Professional footer with branding
    content.extend(create_professional_footer())
    
    # Build PDF
    doc.build(content)
    buffer.seek(0)
    return buffer


def generate_high_confidence_pdf(high_confidence_cards, time_range="3_days"):
    """
    Generate a PDF document with high confidence cards data.
    
    Args:
        high_confidence_cards: List of high confidence card dictionaries with match and prediction data
        time_range: Time range being generated (3_days, 7_days, 15_days, 30_days, 1_month)
    
    Returns:
        BytesIO: PDF file content
    """
    buffer = BytesIO()
    
    # Generate unique document ID
    document_id = str(uuid.uuid4())[:8].upper()
    
    # Custom page function to add watermark and page numbers
    def add_page_footer(canvas, doc):
        # Add page number
        page_num = canvas.getPageNumber()
        canvas.setFont('Helvetica', 9)
        canvas.setFillColor(colors.HexColor('#999999'))
        page_text = f"Page {page_num}"
        text_width = canvas.stringWidth(page_text, 'Helvetica', 9)
        
        # Draw centered at bottom
        canvas.drawString(
            (A4[0] - text_width) / 2,
            0.75 * cm,
            page_text
        )
        
        # Add premium watermark logo with better visibility
        try:
            # Try to find the Bashiri logo in the frontend public directory
            logo_path = os.path.join(os.path.dirname(__file__), '..', '..', 'frontend', 'public', 'bashiri-mark-gold.svg')
            if not os.path.exists(logo_path):
                # Fallback to app icon
                logo_path = os.path.join(os.path.dirname(__file__), '..', '..', 'frontend', 'public', 'bashiri-app-icon-192.png')
            
            if os.path.exists(logo_path):
                canvas.saveState()
                # Set better transparency for visible but subtle watermark
                canvas.setFillAlpha(0.15)  # 15% opacity - more visible
                # Center the logo on the page
                page_width, page_height = A4
                logo = Image(logo_path, width=8*cm, height=8*cm)  # Smaller but cleaner
                logo.drawOn(canvas, (page_width - 8*cm) / 2, (page_height - 8*cm) / 2)
                canvas.restoreState()
        except Exception:
            # If logo not found, skip watermark
            pass
    
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=2*cm,
        leftMargin=2*cm,
        topMargin=2*cm,
        bottomMargin=1.5*cm,  # Reduced for page numbers
        onFirstPage=add_page_footer,
        onLaterPages=add_page_footer
    )
    
    # Custom styles - PREMIUM TYPOGRAPHY
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'CustomTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',  # Using available bold font
        fontSize=28,  # Increased from 24 for more impact
        leading=36,
        textColor=colors.HexColor('#D4AF37'),  # Gold color for premium feel
        alignment=TA_CENTER,
        spaceAfter=0.8*cm,
    )
    
    subtitle_style = ParagraphStyle(
        'CustomSubtitle',
        parent=styles['Heading2'],
        fontName='Helvetica',
        fontSize=14,
        leading=20,
        textColor=colors.HexColor('#999999'),
        alignment=TA_CENTER,
        spaceAfter=1.5*cm,
    )
    
    content = []
    
    # PREMIUM HEADER
    content.append(Paragraph("Bashiri High Confidence Tips", title_style))
    content.append(Paragraph(f"AI Predictions with ≥50% Confidence | {time_range.replace('_', ' ').title()}", subtitle_style))
    
    # Document ID and date
    content.append(Paragraph(
        f"Document ID: {document_id} | Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        ParagraphStyle(
            'Meta',
            fontName='Helvetica',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor('#999999'),
            alignment=TA_CENTER,
            spaceAfter=1.5*cm,
        )
    ))
    
    # Section divider
    content.extend(create_section_divider("High Confidence Picks"))
    
    # Group cards by match
    if high_confidence_cards:
        for card in high_confidence_cards:
            match = card.get('match', {})
            prediction = card.get('data', {}).get('prediction', {})
            
            # Match info - use different field names based on card structure
            home_team = match.get('home_team', {})
            away_team = match.get('away_team', {})
            
            # Handle both dict and object structures
            if isinstance(home_team, dict):
                home_name = home_team.get('name', 'Unknown')
            else:
                home_name = str(home_team) if home_team else 'Unknown'
                
            if isinstance(away_team, dict):
                away_name = away_team.get('name', 'Unknown')
            else:
                away_name = str(away_team) if away_team else 'Unknown'
            
            match_name = f"{home_name} vs {away_name}"
            
            league_obj = match.get('league', {})
            if isinstance(league_obj, dict):
                league = league_obj.get('name', 'Unknown League')
            else:
                league = str(league_obj) if league_obj else 'Unknown League'
            
            kickoff = match.get('kickoff_at', '')
            
            if kickoff:
                try:
                    kickoff_dt = datetime.fromisoformat(kickoff.replace('Z', '+00:00'))
                    kickoff_str = kickoff_dt.strftime('%Y-%m-%d %H:%M')
                except:
                    kickoff_str = 'TBD'
            else:
                kickoff_str = 'TBD'
            
            # Prediction info - handle missing data
            winner = prediction.get('winner', prediction.get('team', 'N/A'))
            if not winner or winner == 'N/A':
                winner = prediction.get('team', 'N/A')
            
            confidence = prediction.get('confidence', 0)
            if confidence is None or confidence == 0:
                confidence = prediction.get('confidence', 0)
            
            market = prediction.get('market_label', prediction.get('market', 'N/A'))
            if not market or market == 'N/A':
                market = prediction.get('market', 'N/A')
            
            # Format winner to be more readable
            if winner == 'home':
                winner_display = home_name
            elif winner == 'away':
                winner_display = away_name
            else:
                winner_display = str(winner).title() if winner else 'N/A'
            
            # Match header
            content.append(Paragraph(
                f"<b>{match_name}</b>",
                ParagraphStyle(
                    'MatchName',
                    fontName='Helvetica-Bold',
                    fontSize=14,
                    leading=18,
                    textColor=colors.white,
                    spaceAfter=0.3*cm,
                )
            ))
            
            # Match details
            content.append(Paragraph(
                f"League: {league} | Kickoff: {kickoff_str}",
                ParagraphStyle(
                    'MatchDetails',
                    fontName='Helvetica',
                    fontSize=10,
                    leading=14,
                    textColor=colors.HexColor('#999999'),
                    spaceAfter=0.5*cm,
                )
            ))
            
            # Prediction table
            prediction_data = [
                ['Selection', 'Market', 'Confidence'],
                [winner_display, market, f"{confidence}%"]
            ]
            
            table = Table(prediction_data, colWidths=[5.5*cm, 4*cm, 2.5*cm])
            table.setStyle(create_premium_table_style())
            
            content.append(table)
            content.append(Spacer(1, 0.8*cm))
    else:
        content.append(Paragraph(
            "No high confidence cards available for this time range.",
            ParagraphStyle(
                'NoData',
                fontName='Helvetica',
                fontSize=12,
                leading=16,
                textColor=colors.HexColor('#999999'),
                alignment=TA_CENTER,
                spaceAfter=1*cm,
            )
        ))
    
    # Professional footer with branding
    content.extend(create_professional_footer())
    
    # Build PDF
    doc.build(content)
    buffer.seek(0)
    return buffer
