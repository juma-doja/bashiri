def create_section_divider(title=""):
    """Create professional section divider with optional title"""
    elements = []
    elements.append(Spacer(1, 0.4*cm))
    
    # Divider line with gold color
    divider_table = Table([['']], colWidths=[18*cm], rowHeights=[0.05*cm])
    divider_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#D4AF37')),
        ('GRID', (0, 0), (-1, -1), 0, colors.white),  # No borders
    ]))
    elements.append(divider_table)
    
    if title:
        elements.append(Spacer(1, 0.3*cm))
        # Section title
        section_title = Paragraph(
            f"<b>{title}</b>",
            ParagraphStyle(
                'SectionTitle',
                fontName='Helvetica-Bold',
                fontSize=12,
                leading=16,
                textColor=colors.HexColor('#D4AF37'),
                spaceAfter=15,
                spaceBefore=10,
            )
        )
        elements.append(section_title)
    
    elements.append(Spacer(1, 0.4*cm))
    return elements


